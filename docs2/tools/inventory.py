#!/usr/bin/env python3
"""Inventory of the .odt manual: what we are moving, file by file.

    python3 docs2/tools/inventory.py <manual dir> [--out docs2/reports]

Writes inventory.json (one row per .odt) and inventory.md (totals per chapter).
Counts words, images, tables and headings straight from each file's content.xml,
so it needs no Pandoc and runs in seconds.
"""
import json
import os
import re
import sys
import zipfile

from lxml import etree

NS = {"text": "urn:oasis:names:tc:opendocument:xmlns:text:1.0",
      "table": "urn:oasis:names:tc:opendocument:xmlns:table:1.0",
      "draw": "urn:oasis:names:tc:opendocument:xmlns:drawing:1.0",
      "xlink": "http://www.w3.org/1999/xlink"}
NAME = re.compile(r"^(\d+(?:\.\d+)*)\s+(.*)\.odt$")


def number_key(num):
    return tuple(int(x) for x in num.split("."))


def scan(path):
    with zipfile.ZipFile(path) as z:
        root = etree.fromstring(z.read("content.xml"))
        media = [n for n in z.namelist() if n.startswith("Pictures/")]
    body = root.find(".//office:body", {"office": "urn:oasis:names:tc:opendocument:xmlns:office:1.0"})
    text = " ".join(t for t in body.itertext())
    images = {im.get(f"{{{NS['xlink']}}}href") for im in body.iterfind(".//draw:image", NS)}
    heads = body.findall(".//text:h", NS)
    levels = {}
    for h in heads:
        lv = h.get(f"{{{NS['text']}}}outline-level") or "1"
        levels[lv] = levels.get(lv, 0) + 1
    return {"words": len(text.split()), "images": len(images), "media_files": len(media),
            "tables": len(body.findall(".//table:table", NS)), "headings": len(heads),
            "heading_levels": dict(sorted(levels.items())),
            "first_heading": "".join(heads[0].itertext()).strip() if heads else ""}


def main(argv):
    if not argv:
        sys.exit(__doc__)
    manual = argv[0]
    out = argv[argv.index("--out") + 1] if "--out" in argv else "docs2/reports"
    rows = []
    for f in sorted(os.listdir(manual)):
        m = NAME.match(f)
        if not m:
            continue
        num, title = m.groups()
        info = scan(os.path.join(manual, f))
        rows.append({"file": f, "src": f[:-4], "number": num, "depth": num.count(".") + 1,
                     "chapter": int(num.split(".")[0]), "title": title, **info})
    rows.sort(key=lambda r: number_key(r["number"]))
    os.makedirs(out, exist_ok=True)
    json.dump({"files": rows}, open(os.path.join(out, "inventory.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)

    chapters = {}
    for r in rows:
        c = chapters.setdefault(r["chapter"], {"title": "", "files": 0, "words": 0, "images": 0, "tables": 0})
        if r["depth"] == 1:
            c["title"] = r["title"]
        c["files"] += 1
        for k in ("words", "images", "tables"):
            c[k] += r[k]
    tot = {k: sum(c[k] for c in chapters.values()) for k in ("files", "words", "images", "tables")}
    md = ["# 📦 Manual inventory", "",
          "Generated by `docs2/tools/inventory.py` from the `.odt` chapters. Words, images and tables per chapter.", "",
          f"**{tot['files']} files · {tot['words']:,} words · {tot['images']:,} images · {tot['tables']:,} tables**", "",
          "| # | Chapter | Files | Words | Images | Tables |", "|---|---|---|---|---|---|"]
    for n in sorted(chapters):
        c = chapters[n]
        md.append(f"| {n} | {c['title']} | {c['files']} | {c['words']:,} | {c['images']:,} | {c['tables']:,} |")
    big = sorted(rows, key=lambda r: -r["words"])[:15]
    md += ["", "## 📏 Largest files", "", "| File | Words | Images |", "|---|---|---|"]
    md += [f"| {r['src']} | {r['words']:,} | {r['images']} |" for r in big]
    open(os.path.join(out, "inventory.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(f"{tot['files']} files, {tot['words']:,} words, {tot['images']:,} images → {out}/inventory.json, inventory.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
